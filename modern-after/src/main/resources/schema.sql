CREATE SEQUENCE BOARD_SEQ START WITH 1;

CREATE TABLE BOARD (
    ID        NUMBER         PRIMARY KEY,
    TITLE     VARCHAR2(200)  NOT NULL,
    WRITER    VARCHAR2(50)   NOT NULL,
    CONTENT   CLOB,
    DEL_YN    CHAR(1)        DEFAULT 'N' NOT NULL,
    REG_DATE  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE BOARD_COMMENT (
    ID        NUMBER         PRIMARY KEY,
    BOARD_ID  NUMBER         NOT NULL REFERENCES BOARD (ID),
    CONTENT   VARCHAR2(1000) NOT NULL
);

-- 목록 조회(삭제 여부 + 최신순)와 댓글 집계에 쓰는 인덱스
CREATE INDEX IDX_BOARD_DEL_ID ON BOARD (DEL_YN, ID);
CREATE INDEX IDX_COMMENT_BOARD ON BOARD_COMMENT (BOARD_ID);
